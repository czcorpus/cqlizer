package tagsets

import (
	_ "embed"
	"encoding/json"
	"sort"
	"strings"
	"sync"
)

// udDataJSON is generated by ./udgen from the UD validator's data
//
//go:embed data/ud_data.json
var udDataJSON []byte

// udUPOSValues is the closed set of universal part-of-speech tags
var udUPOSValues = []string{
	"ADJ", "ADP", "ADV", "AUX", "CCONJ", "DET", "INTJ", "NOUN", "NUM",
	"PART", "PRON", "PROPN", "PUNCT", "SCONJ", "SYM", "VERB", "X",
}

type udDataset struct {

	// feats maps lang -> feature -> permitted values
	feats map[string]map[string][]string

	// deprels maps lang -> permitted relations (incl. subtypes)
	deprels map[string][]string

	// allFeats is a union of feats over all languages
	allFeats map[string][]string

	// allDeprels is a union of deprels over all languages
	allDeprels []string

	// featByLowerName maps lower-cased feature names to the
	// original ones (layered features like `Gender[psor]` excluded)
	featByLowerName map[string]string
}

// featValues returns permitted values of a feature. In case the language
// is known, its specific values are returned and `langSpecific` is true.
// Otherwise, a union of values over all languages is returned.
// The `found` flag tells whether the feature is known at all.
func (d *udDataset) featValues(lang, name string) (values []string, langSpecific, found bool) {
	if lf, ok := d.feats[lang]; ok {
		values, found = lf[name]
		return values, true, found
	}
	values, found = d.allFeats[name]
	return values, false, found
}

// deprelValues returns permitted relations for a language (or a union
// over all languages in case the language is unknown)
func (d *udDataset) deprelValues(lang string) (values []string, langSpecific bool) {
	if ld, ok := d.deprels[lang]; ok {
		return ld, true
	}
	return d.allDeprels, false
}

func sortedKeys[T any](m map[string]T) []string {
	ans := make([]string, 0, len(m))
	for k := range m {
		ans = append(ans, k)
	}
	sort.Strings(ans)
	return ans
}

var udData = sync.OnceValue(func() *udDataset {
	var raw struct {
		Feats   map[string]map[string][]string `json:"feats"`
		Deprels map[string][]string            `json:"deprels"`
	}
	if err := json.Unmarshal(udDataJSON, &raw); err != nil {
		// the data are embedded so this is a programming error
		panic("failed to load embedded UD data: " + err.Error())
	}
	ans := &udDataset{
		feats:           raw.Feats,
		deprels:         raw.Deprels,
		allFeats:        make(map[string][]string),
		featByLowerName: make(map[string]string),
	}
	allFeats := make(map[string]map[string]bool)
	for _, lf := range raw.Feats {
		for name, vals := range lf {
			if allFeats[name] == nil {
				allFeats[name] = make(map[string]bool)
			}
			for _, v := range vals {
				allFeats[name][v] = true
			}
		}
	}
	for name, vals := range allFeats {
		ans.allFeats[name] = sortedKeys(vals)
		if !strings.Contains(name, "[") {
			ans.featByLowerName[strings.ToLower(name)] = name
		}
	}
	allDeprels := make(map[string]bool)
	for _, ld := range raw.Deprels {
		for _, d := range ld {
			allDeprels[d] = true
		}
	}
	ans.allDeprels = sortedKeys(allDeprels)
	return ans
})
